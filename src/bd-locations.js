// Flat list of all 64 districts in alphabetical order
export const BD_DISTRICTS = BD_DIVISIONS.flatMap(div => 
  div.districts.map(d => ({
    name: d.name,
    division: div.name,
    upazilas: d.upazilas
  }))
).sort((a, b) => a.name.localeCompare(b.name));

export function getUpazilasForDistrict(districtName) {
  if (!districtName) return [];
  const found = BD_DISTRICTS.find(d => d.name.toLowerCase() === districtName.trim().toLowerCase());
  return found ? found.upazilas : [];
}

/**
 * Validates Bangladeshi mobile phone numbers.
 * Valid prefixes: 013, 014, 015, 016, 017, 018, 019.
 * Accepts:
 * - 01[3-9]\d{8} (11 digits, e.g. 01712345678)
 * - +8801[3-9]\d{8} (14 characters, e.g. +8801712345678)
 * - 8801[3-9]\d{8} (13 digits, e.g. 8801712345678)
 */
export function isValidBdPhoneNumber(phone) {
  if (typeof phone !== 'string') return false;
  const cleaned = phone.trim().replace(/[\s\-()]/g, '');
  return /^(?:\+?8801|01)[3-9]\d{8}$/.test(cleaned);
}

/**
 * Standardizes BD phone number to 11-digit format (01XXXXXXXXX).
 */
export function formatBdPhoneNumber(phone) {
  if (typeof phone !== 'string') return '';
  const cleaned = phone.trim().replace(/[\s\-()]/g, '');
  if (/^01[3-9]\d{8}$/.test(cleaned)) return cleaned;
  if (/^\+8801[3-9]\d{8}$/.test(cleaned)) return '0' + cleaned.slice(4);
  if (/^8801[3-9]\d{8}$/.test(cleaned)) return '0' + cleaned.slice(3);
  return cleaned;
}
